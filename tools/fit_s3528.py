#!/usr/bin/env python3
"""Reproducible constrained curve fit. Only fit-split readings enter the objective.

Seven stable poles, two nominal notch pairs; no claim of recovered topology.
Bilinear core at40fc plus cosine prefilter and sample/hold observation factors.
"""
import numpy as np
from scipy import signal,optimize
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
reference=json.loads((root/'data/s3528b_1993_reference.json').read_text())
D=np.array([[r['frequency_hz'],r['delay_us']] for r in reference['group_delay']])
L=np.array([[r['frequency_hz'],r['loss_db']] for r in reference['stopband_loss']])
dmask=np.array([r['split']=='fit' for r in reference['group_delay']])
lmask=np.array([r['split']=='fit' for r in reference['stopband_loss']])

def zpk(t):
 p0,*v=t; ps=[-p0]
 for wp,q in np.reshape(v,(3,2)):
  ps.extend(np.roots([1,wp/q,wp*wp]))
 z=np.array([1.325j,-1.325j,1.62j,-1.62j]);p=np.array(ps);k=np.real(np.prod(-p)/np.prod(-z));return z,p,k

def response(t,w):
 z,p,k=zpk(t);w=np.asarray(w);omega=np.tan(np.pi*w/40)/np.tan(np.pi/40);s=np.asarray(1j*omega)
 h=k*np.prod(s[...,None]-z,axis=-1)/np.prod(s[...,None]-p,axis=-1)
 h*=np.cos(np.pi*w/80)*np.sinc(w/40)
 der=(np.pi/40/np.tan(np.pi/40))/(np.cos(np.pi*w/40)**2)
 gd=-np.imag(1j*der*(np.sum(1/(s[...,None]-z),axis=-1)-np.sum(1/(s[...,None]-p),axis=-1)))/(2*np.pi)+3/160
 return 20*np.log10(np.maximum(abs(h),1e-20)),gd/3200*1e6

def residual(t):
 b=np.linspace(0,1,121);db,_=response(t,b);db-=response(t,.6)[0]
 loss,_=response(t,L[lmask,0]/3200)
 _,gd=response(t,D[dmask,0]/3200)
 edge,_=response(t,np.array([1.06,1.27,1.3,1.32]))
 # Near-notch table values are typical finite depths, not infinite ideal zeros.
 return np.r_[(gd-D[dmask,1])/30,(loss+L[lmask,1])/1.5,(edge+np.array([3,42,51,65]))/np.array([.75,3,3,5]),np.maximum(abs(db)-.095,0)/.01, np.maximum(response(t,np.linspace(1.3,6.1,300))[0]+51,0)/.5]
bounds=([.1,.2,.3,.4,.5,.8,1],[3,1,6,1.2,20,1.3,80])
def fit():
    best=None
    for seed in range(3):
        rng=np.random.default_rng(seed)
        x=np.array([.55,.6,.8,.9,2,1.03,10])*(1+rng.uniform(-.08,.08,7))
        r=optimize.least_squares(residual,x,bounds=bounds,max_nfev=1500,xtol=1e-12,ftol=1e-12,gtol=1e-12)
        if best is None or np.linalg.norm(r.fun)<np.linalg.norm(best.fun):best=r
    return best.x

def coefficients(params):
    z,p,k=zpk(params);scale=80*np.tan(np.pi/40)
    zd,pd,kd=signal.bilinear_zpk(z*scale,p*scale,k*scale**3,fs=40)
    return signal.zpk2sos(zd,pd,kd)

def report(params):
    records=[]
    for name,rows,mask in [('group_delay',D,dmask),('stopband_loss',L,lmask)]:
        db,gd=response(params,rows[:,0]/3200)
        predicted=gd if name=='group_delay' else -db
        for i,(row,value) in enumerate(zip(rows,predicted)):
            records.append({'kind':name,'frequency_hz':float(row[0]),'observed':float(row[1]),'predicted':float(value),
                            'error':float(value-row[1]),'split':'fit' if mask[i] else 'holdout'})
    summaries={}
    for name in ('group_delay','stopband_loss'):
        for split in ('fit','holdout'):
            errors=np.array([r['error'] for r in records if r['kind']==name and r['split']==split])
            summaries[name+'_'+split]={'max_abs':float(max(abs(errors))),'rms':float(np.sqrt(np.mean(errors**2)))}
    w=np.linspace(0,1,10001);db,_=response(params,w);db-=response(params,.6)[0]
    summaries['relative_passband_max_abs_db']=float(max(abs(db)))
    return {'provenance':reference['provenance'],'source_sha256':reference['source_sha256'],
            'parameters':[float(x) for x in params],'summaries':summaries,'records':records}

if __name__=='__main__':
    import argparse
    parser=argparse.ArgumentParser(description='Fit a nominal seven-pole/two-notch model to AMI1993 typical curves; not hardware calibration')
    parser.add_argument('--plot',action='store_true',help='Write a source SVG comparison figure')
    parser.add_argument('--write',action='store_true',help='Write coefficients and validation report into this repository')
    args=parser.parse_args();params=fit();sos=coefficients(params);result=report(params)
    if args.write:
        header='// Generated by tools/fit_s3528.py --write; AMI1993 typical-curve fit.\n// Not recovered chip coefficients or physical hardware calibration.\n#pragma once\nnamespace eii::analog {\ninline constexpr double s3528Ami1993Sos[4][5]={\n'
        for row in sos:header+='    {'+','.join(format(float(row[i]),'.17g') for i in (0,1,2,4,5))+'},\n'
        header+='};\n}\n';(root/'src/s3528_curve_coefficients.h').write_text(header)
        (root/'validation/s3528-curve-fit.json').write_text(json.dumps(result,indent=2)+'\n')
    if args.plot:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        matplotlib.rcParams.update({'svg.fonttype':'none','svg.hashsalt':'eii-s3528-1993-fit'})
        fig,axes=plt.subplots(1,3,figsize=(13,3.9),layout='constrained')
        generic=signal.ellip(7,.1,51,.05,output='sos')
        def old_response(w):
            _,h=signal.sosfreqz(generic,worN=2*np.pi*w/40)
            return h*np.cos(np.pi*w/80)*np.sinc(w/40)*np.exp(-1j*2*np.pi*w*3/160)
        for axis,limits in zip(axes[:2],[(.05,1.8),(1.8,6.25)]):
            w=np.linspace(*limits,1800);new,_=response(params,w)
            axis.plot(w,20*np.log10(abs(old_response(w))),label='Generic elliptic',color='#999999')
            axis.plot(w,new,label='AMI1993 curve fit',color='#087f8c');axis.set(xlabel='Frequency / nominal fc',ylabel='Gain (dB)',ylim=(-90,2));axis.grid(alpha=.25)
            for split,marker in [('fit','o'),('holdout','s')]:
                rows=[r for r in reference['stopband_loss'] if r['split']==split]
                axis.scatter([r['frequency_hz']/3200 for r in rows],[-r['loss_db'] for r in rows],marker=marker,s=25,color='#c77400',label='Plot '+split)
        w=np.linspace(.03,1.12,1500);_,new=response(params,w)
        old=old_response(w);old_delay=-np.gradient(np.unwrap(np.angle(old)),w)/(2*np.pi)*1e6/3200
        axes[2].plot(w,old_delay,color='#999999');axes[2].plot(w,new,color='#087f8c')
        for split,marker in [('fit','o'),('holdout','s')]:
            rows=[r for r in reference['group_delay'] if r['split']==split]
            axes[2].errorbar([r['frequency_hz']/3200 for r in rows],[r['delay_us'] for r in rows],yerr=30,fmt=marker,ms=3,color='#c77400',alpha=.8)
        axes[2].set(xlabel='Frequency / nominal fc',ylabel='Group delay at fc=3.2kHz (us)',ylim=(0,1600));axes[2].grid(alpha=.25)
        axes[0].legend(fontsize=7,loc='lower left');axes[0].set_xlim(.05,1.8);axes[1].set_xlim(1.8,6.25)
        fig.suptitle('Manufacturer typical-curve fit; not physical hardware calibration',fontsize=11)
        (root/'docs/figures').mkdir(exist_ok=True)
        fig.savefig(root/'docs/figures/s3528-response-fit.svg',metadata={'Date':None})
        fig.savefig('/tmp/s3528-response-fit.png',dpi=140)
    print(json.dumps(result['summaries'],indent=2))
